-- Class Activity 3 · users and activity tables
-- Run AFTER ca3_titles_vectors.sql and ca3_search_phrases.sql
-- (activity has a foreign key to titles, so titles must already exist).
-- Safe to run again: tables and indexes are only created if missing.

-- ---------------------------------------------------------------
-- users: structured profile data in ordinary columns,
--        per-user viewing preferences in JSONB
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    user_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    f_name              text  NOT NULL,
    l_name              text  NOT NULL,
    email               text  NOT NULL UNIQUE,
    country             text  NOT NULL,
    plan                text  NOT NULL,
    viewing_preferences jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT preferences_is_object CHECK (jsonb_typeof(viewing_preferences) = 'object')
);

-- Example viewing_preferences document:
-- {"favourite_genres": ["Mystery", "Sci-fi"],
--  "subtitle_language": "fr",
--  "parental_controls": {"enabled": true, "max_rating": "PG-13"}}

-- ---------------------------------------------------------------
-- activity: one row per event; event details stored as JSONB.
-- title_id is nullable because some events (e.g. search) are not
-- about a specific title.
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS activity (
    activity_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      integer     NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    title_id     integer              REFERENCES titles (title_id),
    occurred_at  timestamptz NOT NULL DEFAULT now(),
    events_data  jsonb       NOT NULL,
    CONSTRAINT events_data_has_type CHECK (events_data ? 'type')
);

-- Example events_data documents (each type records different details):
-- play:   {"type": "play",   "minutes_watched": 42, "device": "tv"}
-- rate:   {"type": "rate",   "stars": 4}
-- search: {"type": "search", "query": "something scary", "results_clicked": 2}

-- ---------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------
-- GIN index on each JSONB column (required by the activity brief).
CREATE INDEX IF NOT EXISTS users_preferences_gin ON users    USING gin (viewing_preferences);
CREATE INDEX IF NOT EXISTS activity_events_gin   ON activity USING gin (events_data);

-- Ordinary B-tree indexes on the foreign keys, for joins.
CREATE INDEX IF NOT EXISTS activity_user_idx  ON activity (user_id, occurred_at);
CREATE INDEX IF NOT EXISTS activity_title_idx ON activity (title_id);
